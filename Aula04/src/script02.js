// Operadores de Atribuição

//  Operador Atribuidor de adição
let a = 5;
a += 10;  //É o mesmo que: a = a + 10
console.log(a);

console.log(" ");

// Operador Atribuidor de subtração
let b = 10;
b -= 7; // É o mesmo que: b = b - 7

console.log(b);

console.log(" ");

// Operador Atribuuidor de multiplicação
let c = 3;
c *= 3; // É o mesmo que: c = c * 3 
console.log(c);

console.log(" ");

// Operador Atribuidor de Divisão
let d = 8;
d /= 4; // É o mesmo que: d = d / 4
console.log(d);

console.log(" ");

// Operador Atribuidor de Exponenciação
let e = 100;
e **= 2; // É o mesmo que: e = e ** 2
console.log(e);

console.log(" ");

// Operador Atribuidor de Resto (Módulo)
let f = 10;
f %= 5; // É o mesmo que: f = f % 5
console.log(f);

console.log(" ");

